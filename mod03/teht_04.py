# kolmen luvun summa, tulo, keskiarvo

luku = float(input('anna luku: '))
luku2 = float(input('anna toinen luku: '))
luku3 = float(input('anna kolmas luku: '))

print(f'lukujen summa on {luku+luku2+luku3} yksikköä.')
print(f'lukujen tulo on {luku*luku2*luku3} yksikköä.')
print(f'lukujen keskiarvo on {(luku+luku2+luku3)/3} yksikköä.')
